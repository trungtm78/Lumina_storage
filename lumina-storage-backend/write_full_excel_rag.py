CELL_ADD_HIERARCHY = [
    "def add_hierarchy_cols(df, bolds, schema):\n",
    "    kc = schema.get('key_columns', {})\n",
    "    entity_col = kc.get('entity_name', df.columns[0])\n",
    "    has_hier   = schema.get('has_hierarchy', False)\n",
    "    if entity_col not in df.columns:\n",
    "        entity_col = df.columns[0]\n",
    "    if not has_hier:\n",
    "        df = df.copy()\n",
    "        df.insert(0, '__store__',    df[entity_col].astype(str))\n",
    "        df.insert(1, '__category__', None)\n",
    "        return df\n",
    "    current, stores, cats = None, [], []\n",
    "    for i, (_, row) in enumerate(df.iterrows()):\n",
    "        bold = bolds[i] if i < len(bolds) else False\n",
    "        val  = str(row[entity_col]).strip()\n",
    "        if bold:\n",
    "            current = val\n",
    "            stores.append(val)\n",
    "            cats.append(None)\n",
    "        else:\n",
    "            stores.append(current)\n",
    "            cats.append(val)\n",
    "    df = df.copy()\n",
    "    df.insert(0, '__store__',    stores)\n",
    "    df.insert(1, '__category__', cats)\n",
    "    return df\n",
    "\n",
    "\n",
    "dfs = {}\n",
    "for name, df in all_dfs.items():\n",
    "    dfs[name] = add_hierarchy_cols(df, all_bolds[name], all_schemas[name])\n",
    "    print(f'{name!r}: {dfs[name].shape}  cats={dfs[name][\"__category__\"].dropna().unique()[:3].tolist()}')\n",
]

