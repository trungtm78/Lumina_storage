    "resp_e = litellm.embedding(model=embed_cfg['model'], input=schema_texts, **kw_e)\n",
    "schema_embeddings = np.array([item['embedding'] for item in resp_e.data])\n",
    "print(f'Schema embeddings: {schema_embeddings.shape}')\n",
    "\n",
    "def find_relevant_sheets(question, top_k=2):\n",
    "    kw = {k:v for k,v in embed_cfg.items() if k != 'model' and v is not None}\n",
    "    r  = litellm.embedding(model=embed_cfg['model'], input=[question], **kw)\n",
    "    q  = np.array(r.data[0]['embedding'])\n",
    "    norms = np.linalg.norm(schema_embeddings, axis=1) * np.linalg.norm(q)\n",
    "    sims  = schema_embeddings @ q / np.where(norms==0, 1e-9, norms)\n",
    "    top   = np.argsort(sims)[::-1][:top_k]\n",
    "    return [(sheet_names_ordered[i], float(sims[i])) for i in top]\n",
    "\n",
    "# Test routing\n",
    "for q in [\n",
    "    'Doanh thu cua hang 98 Nguyen Van Troi thang 1?',\n",
    "    'Banh huy cong ty thang 1?',\n",
    "    'So sanh doanh thu Noel nam nay voi nam ngoai?',\n",
    "]:\n",
    "    hits = find_relevant_sheets(q, top_k=2)\n",
    "    print(f'Q: {q}')\n",
    "    for n, s in hits: print(f'  -> {n!r}  {s:.3f}')\n",
